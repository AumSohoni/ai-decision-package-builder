from __future__ import annotations

import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from pydantic import ValidationError

from .models import CompletenessReport, DecisionPackage, RiskCase, SimilarCase, Status


class FakeLLMClient:
    def __init__(self, response: Dict[str, Any] | None = None):
        self.response = response
        self.calls = 0

    def generate(self, prompt: str) -> str:
        self.calls += 1
        if self.response is not None:
            return json.dumps(self.response)
        # Default minimal valid response
        pkg = {
            "package_id": f"PKG-{uuid.uuid4().hex[:8].upper()}",
            "risk_case_id": "RC-000",
            "summary": "Automated summary based on provided information.",
            "completeness_report": {
                "is_complete": False,
                "missing": [],
                "completeness_score": 50,
                "notes": ["Generated by fake client."],
            },
            "missing_information": [],
            "similar_cases": [],
            "questions_for_experts": ["Please confirm mitigation feasibility."],
            "status": "draft",
        }
        return json.dumps(pkg)


class LLM:
    def __init__(self, client=None, model: str = "gpt-4o-mini", temperature: float = 0.0):
        self.client = client
        self.model = model
        self.temperature = temperature

    def _build_prompt(
        self,
        risk_case: RiskCase | dict,
        completeness_report: CompletenessReport | dict,
        similar_cases: List[SimilarCase] | List[dict],
    ) -> str:
        if isinstance(risk_case, RiskCase):
            rc = risk_case.model_dump()
        else:
            rc = dict(risk_case)
        if isinstance(completeness_report, CompletenessReport):
            cr = completeness_report.model_dump()
        else:
            cr = dict(completeness_report)
        sc = []
        for s in similar_cases:
            if isinstance(s, SimilarCase):
                sc.append(s.model_dump())
            else:
                sc.append(dict(s))

        return json.dumps(
            {
                "instruction": (
                    "You are preparing a structured decision package for human review. "
                    "Return ONLY valid JSON matching the DecisionPackage schema. "
                    "You may ONLY cite past cases whose ids are in 'retrieved_similar_case_ids'. "
                    "Do not invent past cases. Do not approve or reject. "
                    "Keep status as 'draft' unless explicitly told otherwise."
                ),
                "risk_case": rc,
                "completeness_report": cr,
                "retrieved_similar_cases": sc,
                "retrieved_similar_case_ids": [s["id"] for s in sc],
            },
            indent=2,
        )

    def generate_package(
        self,
        risk_case: RiskCase | dict,
        completeness_report: CompletenessReport | dict,
        similar_cases: List[SimilarCase] | List[dict],
        max_retries: int = 1,
    ) -> DecisionPackage:
        prompt = self._build_prompt(risk_case, completeness_report, similar_cases)

        for attempt in range(max_retries + 1):
            try:
                if self.client is None:
                    # Try to use real clients if keys exist
                    api_key = os.getenv("OPENAI_API_KEY") or os.getenv("ANTHROPIC_API_KEY")
                    if not api_key:
                        raise RuntimeError(
                            "No LLM client provided and no API key found in environment."
                        )
                    # For simplicity, default to OpenAI if OPENAI key present
                    if os.getenv("OPENAI_API_KEY"):
                        from openai import OpenAI

                        self.client = OpenAI()
                        resp = self.client.chat.completions.create(
                            model=self.model,
                            temperature=self.temperature,
                            messages=[{"role": "user", "content": prompt}],
                            response_format={"type": "json_object"},
                        )
                        content = resp.choices[0].message.content
                    else:
                        from anthropic import Anthropic

                        self.client = Anthropic()
                        resp = self.client.messages.create(
                            model="claude-3-5-sonnet-20241022",
                            temperature=self.temperature,
                            max_tokens=2048,
                            messages=[{"role": "user", "content": prompt}],
                        )
                        # Anthropic returns content blocks
                        content = resp.content[0].text if resp.content else "{}"
                else:
                    # Assume client has generate(prompt) or is OpenAI-like; support FakeLLMClient
                    if hasattr(self.client, "generate"):
                        content = self.client.generate(prompt)
                    elif hasattr(self.client, "chat") and hasattr(
                        self.client.chat, "completions"
                    ):
                        resp = self.client.chat.completions.create(
                            model=self.model,
                            temperature=self.temperature,
                            messages=[{"role": "user", "content": prompt}],
                            response_format={"type": "json_object"},
                        )
                        content = resp.choices[0].message.content
                    else:
                        raise RuntimeError("Unsupported LLM client interface.")
            except Exception as e:
                if attempt == max_retries:
                    raise e
                continue  # retry

            try:
                data = json.loads(content)
            except json.JSONDecodeError as e:
                if attempt == max_retries:
                    raise e
                continue  # retry

            # Enforce: only cited ids from retrieved set
            retrieved_ids = set()
            for s in similar_cases:
                if isinstance(s, SimilarCase):
                    retrieved_ids.add(s.id)
                else:
                    retrieved_ids.add(s.get("id"))
            cited = data.get("similar_cases", [])
            for c in cited:
                cid = c.get("id") if isinstance(c, dict) else None
                if cid and cid not in retrieved_ids:
                    if attempt == max_retries:
                        raise ValueError(
                            f"Cited case id '{cid}' not in retrieved similar cases set."
                        )
                    # Try to regenerate
                    data["similar_cases"] = []
                    data["status"] = "draft"
                    content = json.dumps(data)
                    # Let validation catch if needed; retry loop will re-parse/validate
                    continue

            try:
                pkg = DecisionPackage.model_validate(data)
            except ValidationError as e:
                if attempt == max_retries:
                    raise e
                continue  # retry
            return pkg

        raise RuntimeError("Failed to generate valid decision package.")
